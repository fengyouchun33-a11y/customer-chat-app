/// Localized display name of a target language under the App UI locale
/// [uiCode]. Falls back to the English name (from [kVisitorLangs]), then the
/// raw code. English UI has no table entry, so it naturally shows English.
String visitorLangLocalized(String code, String uiCode) {
  final m = _uiLangNames[uiCode];
  if (m != null) {
    final n = m[code];
    if (n != null && n.isNotEmpty) return n;
  }
  for (final l in kVisitorLangs) {
    if (l.code == code) return l.english;
  }
  return code;
}
